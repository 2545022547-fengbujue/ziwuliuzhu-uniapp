const fs = require('fs')
const path = require('path')

const projectDir = path.resolve(__dirname, '..')
const fontDir = path.join(projectDir, 'src', 'assets', 'fonts')

const fonts = [
  {
    exportName: 'kaitiGB2312Base64',
    source: 'kaiti-gb2312.ttf',
    target: 'kaiti-gb2312-base64.txt'
  },
  {
    exportName: 'wenYuanSerifBase64',
    source: 'wenjinmincho-subset-v6.ttf',
    target: 'wenjinmincho-subset-v6-base64.txt'
  },
  {
    exportName: 'wenYuanSerifBoldBase64',
    source: 'WenYuanSerifSC-Bold-subset-v2.ttf',
    target: 'bold-v2-base64.txt'
  },
  {
    exportName: 'lxgwZhenKaiSlabBase64',
    source: 'LXGWZhenKaiSlabGB-subset.ttf',
    target: 'lxgw-zhenkai-slab-base64.txt'
  }
]

function writeIfChanged(targetPath, content) {
  if (fs.existsSync(targetPath)) {
    const current = fs.readFileSync(targetPath, 'utf8')
    if (current === content) {
      return false
    }
  }

  fs.writeFileSync(targetPath, content, 'utf8')
  return true
}

const generatedExports = []

for (const font of fonts) {
  const sourcePath = path.join(fontDir, font.source)
  const targetPath = path.join(fontDir, font.target)

  if (!fs.existsSync(sourcePath)) {
    throw new Error(`Font file not found: ${sourcePath}`)
  }

  const base64 = fs.readFileSync(sourcePath).toString('base64')
  generatedExports.push({ name: font.exportName, base64 })

  const changed = writeIfChanged(targetPath, base64)
  const status = changed ? 'updated' : 'unchanged'

  console.log(`${status}: ${font.target} (${base64.length} chars)`)
}

const generatedModulePath = path.join(fontDir, 'mp-font-base64.generated.js')
const generatedModule = [
  '// This file is generated by scripts/sync-font-base64.js.',
  '// Do not edit it by hand.',
  ...generatedExports.map(({ name, base64 }) => `export const ${name} = ${JSON.stringify(base64)}`),
  ''
].join('\n')

const moduleChanged = writeIfChanged(generatedModulePath, generatedModule)
console.log(`${moduleChanged ? 'updated' : 'unchanged'}: mp-font-base64.generated.js`)
